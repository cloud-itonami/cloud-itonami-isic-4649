    (println "wrote" out "(" (count ledger) "ledger facts,"
             (count hs) "HARD holds,"
             (count (filter #(= :approval-granted (:t %)) audit)) "approvals,"
             (count (store/dispatch-history db)) "dispatch drafts,"
             (count (store/invoice-history db)) "invoice drafts )")))
