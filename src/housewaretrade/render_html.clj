        {:keys [db audit] :as run} (run-demo!)
        ledger (vec (store/ledger db))
        hs (holds ledger)]
    (when (empty? hs)
      (throw (ex-info "no :governor-hold fact on the ledger — refusing to write a console that shows no real hold"
                      {:ledger-facts (count ledger)})))
